#!/usr/bin/env bash
# =============================================================================
# Render the MT5 autostart config from environment variables.
#
# Produces:
#   $OUT_DIR/terminal.ini    -> pass to terminal64.exe via /config:
#   $OUT_DIR/mt5_bridge.set  -> copy into <data>\MQL5\Presets\
#
# Values are read from the single repository-root .env (the same file the Rust
# engine reads), so credentials and the pipe secret stay in sync. Set
# MT5_ENV_FILE to use a different file; variables already exported in the
# environment take precedence over .env values.
#
# Usage:
#   ./render_config.sh [OUT_DIR]
#
# All variables are optional except MT5_PIPE_SECRET. Defaults are shown below.
# =============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT_DIR="${1:-$SCRIPT_DIR}"

# shellcheck source=env.sh
source "$SCRIPT_DIR/env.sh"
load_mt5_env "${MT5_ENV_FILE:-$SCRIPT_DIR/../../.env}"

MT5_LOGIN="${MT5_LOGIN:-}"
MT5_PASSWORD="${MT5_PASSWORD:-}"
MT5_SERVER="${MT5_SERVER:-}"
MT5_PIPE_SECRET="${MT5_PIPE_SECRET:-}"
MT5_PIPE_NAME="${MT5_PIPE_NAME:-mt5bridge}"
MT5_SYMBOL="${MT5_SYMBOL:-EURUSD}"
MT5_PERIOD="${MT5_PERIOD:-M1}"
MT5_MAGIC="${MT5_MAGIC:-20240101}"
MT5_MAX_VOLUME="${MT5_MAX_VOLUME:-10.0}"
MT5_MAX_DEVIATION="${MT5_MAX_DEVIATION:-100}"
MT5_SERVER_UTC_OFFSET="${MT5_SERVER_UTC_OFFSET:-2}"
# Monotonic config version used to refresh an already-running bridge instance.
# Defaults to the current Unix time; override for reproducible deployments.
MT5_CONFIG_GENERATION="${MT5_CONFIG_GENERATION:-$(date +%s)}"

if [[ -z "$MT5_PIPE_SECRET" ]]; then
    echo "error: MT5_PIPE_SECRET must be set (it must match the Rust engine)" >&2
    exit 1
fi

# Truthy -> true for the EA's boolean inputs.
case "${MT5_LIVE_ACK:-0}" in
    1|true|TRUE|yes|YES|on|ON) LIVE_ACK=true ;;
    *)                          LIVE_ACK=false ;;
esac

# Accept either the enum name or its numeric value.
case "${MT5_SERVER_TIME_CONVENTION:-new_york_dst}" in
    0|fixed|FIXED)                   SERVER_TIME_CONVENTION=0 ;;
    2|europe_dst|EUROPE_DST)         SERVER_TIME_CONVENTION=2 ;;
    *)                               SERVER_TIME_CONVENTION=1 ;;
esac

mkdir -p "$OUT_DIR"
umask 077

cat > "$OUT_DIR/terminal.ini" <<EOF
; Generated by mql5/autostart/render_config.sh — contains credentials.
[Common]
EOF
# Only emit credentials that were supplied; omitted keys fall back to the
# terminal's saved account database (useful when the account is already cached).
if [[ -n "$MT5_LOGIN" ]];    then echo "Login=${MT5_LOGIN}"       >> "$OUT_DIR/terminal.ini"; fi
if [[ -n "$MT5_PASSWORD" ]]; then echo "Password=${MT5_PASSWORD}" >> "$OUT_DIR/terminal.ini"; fi
if [[ -n "$MT5_SERVER" ]];   then echo "Server=${MT5_SERVER}"     >> "$OUT_DIR/terminal.ini"; fi
cat >> "$OUT_DIR/terminal.ini" <<EOF
KeepPrivate=1

[Experts]
AllowLiveTrading=1
AllowDllImport=1
Enabled=1
Account=0
Profile=0

[StartUp]
Expert=mt5_bridge
ExpertParameters=mt5_bridge.set
Symbol=${MT5_SYMBOL}
Period=${MT5_PERIOD}
EOF

cat > "$OUT_DIR/mt5_bridge.set" <<EOF
InpMagicNumber=${MT5_MAGIC}
InpPipeName=${MT5_PIPE_NAME}
InpPipeSecret=${MT5_PIPE_SECRET}
InpRequireSecret=true
InpEnforceMagicNumber=true
InpConvertToUTC=true
InpServerTimeConvention=${SERVER_TIME_CONVENTION}
InpServerUtcOffsetHours=${MT5_SERVER_UTC_OFFSET}
InpTimerIntervalMs=1
InpMaxRequestsPerTimer=64
InpMaxTimerBudgetUs=5000
InpAutoSelectSymbols=true
InpConfigGeneration=${MT5_CONFIG_GENERATION}
InpTakeoverTimeoutMs=5000
InpCloseStaleCharts=true
InpEnableKillSwitch=false
InpRequireLiveAck=true
InpLiveAckAcknowledged=${LIVE_ACK}
InpMaxVolumePerOrder=${MT5_MAX_VOLUME}
InpMaxDeviation=${MT5_MAX_DEVIATION}
EOF

chmod 600 "$OUT_DIR/terminal.ini" "$OUT_DIR/mt5_bridge.set"

echo "Wrote:"
echo "  $OUT_DIR/terminal.ini"
echo "  $OUT_DIR/mt5_bridge.set"
echo
echo "Install the preset into the terminal data folder, then start with /config:"
echo "  cp '$OUT_DIR/mt5_bridge.set' '<Terminal_Data_Folder>/MQL5/Presets/mt5_bridge.set'"
echo "  terminal64.exe /config:\"$OUT_DIR/terminal.ini\""
